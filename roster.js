// إرجاع اسم المتطوع حسب الجنس والرقم (الرقم يبدأ من 1)
export function lookupVolunteer(gender, number){
  const list = gender === "boys" ? BOYS : GIRLS;
  const idx = parseInt(number, 10) - 1;
  if(isNaN(idx) || idx < 0 || idx >= list.length) return null;
  return list[idx];
}
